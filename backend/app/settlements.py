class SettlementLocator:
    """
    Singleton spatial index for fast official administrative hierarchy resolution.
    Pre-indexes all settlements in a KD-Tree to answer queries in microseconds.
    """
    _instance: Optional["SettlementLocator"] = None

    def __init__(self):
        self.settlements = NORTHEAST_SETTLEMENTS
        coords = np.array([[s["lat"], s["lon"]] for s in self.settlements])
        self.tree = cKDTree(coords)

        # State-specific trees for 100% accurate intra-state address resolution
        self.state_trees: Dict[str, Any] = {}
        state_settlements: Dict[str, List[Dict[str, Any]]] = {}
        for s in self.settlements:
            st = s["state"]
            if st not in state_settlements:
                state_settlements[st] = []
            state_settlements[st].append(s)

        for st, st_list in state_settlements.items():
            st_coords = np.array([[s["lat"], s["lon"]] for s in st_list])
            self.state_trees[st] = (cKDTree(st_coords), st_list)

    @classmethod
    def get_instance(cls) -> "SettlementLocator":
        if cls._instance is None:
            cls._instance = cls()
        return cls._instance

    def find_nearest_settlement(self, lat: float, lon: float, state: Optional[str] = None) -> Dict[str, Any]:
        """
        Returns full authentic administrative jurisdiction:
        village, subdivision, district, state, pincode, full_address, and short_address.
        Prioritizes settlements within the same state if provided.
        """
        if state and state in self.state_trees:
            st_tree, st_list = self.state_trees[state]
            dist_deg, idx = st_tree.query([lat, lon])
            place = st_list[idx]
        else:
            dist_deg, idx = self.tree.query([lat, lon])
            place = self.settlements[idx]

        dist_km = haversine_distance_km(lat, lon, place["lat"], place["lon"])

        v_name = place["village"]
        sub_div = place["subdivision"]
        dist_name = place["district"]
        st_name = place["state"]
        pin = place["pincode"]

        # Structured official administrative address (No casual 'Near')
        full_addr = f"{v_name}, {sub_div}, {dist_name}, {st_name} - {pin}"
        short_addr = f"{v_name}, {sub_div} ({dist_name})"

        return {
            "village": v_name,
            "subdivision": sub_div,
            "district": dist_name,
            "state": st_name,
            "pincode": pin,
            "full_address": full_addr,
            "short_address": short_addr,
            "place_type": place["type"],
            "place_distance_km": round(dist_km, 1),
            # Backward compatibility aliases
            "nearest_place": v_name,
            "location_name": short_addr,
        }


settlement_locator = SettlementLocator.get_instance()
